// Creates deploy/.env with fresh secrets for a self-hosted installation.
//
//   node deploy/init.mjs                         # http://localhost:8080, local mail catcher
//   node deploy/init.mjs https://vendors.example.com
//
// Never overwrites an existing deploy/.env: the secrets in it encrypt and sign your data.
// Works on Windows, macOS and Linux with Node 22 or later; no packages needed.
import { createHmac, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const file = join(dirname(fileURLToPath(import.meta.url)), '.env');
if (existsSync(file)) {
  console.error(`${file} already exists. Delete it only if you are starting from an empty database.`);
  process.exit(1);
}

const publicUrl = (process.argv[2] ?? 'http://localhost:8080').replace(/\/+$/, '');
if (!/^https?:\/\/[A-Za-z0-9.:-]+$/.test(publicUrl)) {
  console.error('Give the address as an origin, for example https://vendors.example.com');
  process.exit(1);
}
const local = /^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(publicUrl);
const port = new URL(publicUrl).port || (local ? '80' : '8080');

const secret = (bytes) => randomBytes(bytes).toString('base64url');
const b64 = (value) => Buffer.from(JSON.stringify(value)).toString('base64url');
const jwtSecret = secret(48);
/** Long-lived API keys in the format Supabase uses for self-hosting (HS256). */
function apiKey(role) {
  const now = Math.floor(Date.now() / 1000);
  const body = `${b64({ alg: 'HS256', typ: 'JWT' })}.${b64({ role, iss: 'supabase', iat: now, exp: now + 10 * 365 * 24 * 3600 })}`;
  return `${body}.${createHmac('sha256', jwtSecret).update(body).digest('base64url')}`;
}

const lines = [
  '# Generated by deploy/init.mjs. Keep this file private and back it up: it is git-ignored',
  '# and holds the keys that sign sessions and encrypt saved integration secrets.',
  '',
  `PUBLIC_URL=${publicUrl}`,
  `APP_PORT=${port}`,
  '# 127.0.0.1 = reachable from this machine only. Use 0.0.0.0 behind your own TLS proxy.',
  'APP_BIND=127.0.0.1',
  `ENABLE_HSTS=${publicUrl.startsWith('https://') ? 'true' : 'false'}`,
  '',
  `POSTGRES_PASSWORD=${secret(32)}`,
  `JWT_SECRET=${jwtSecret}`,
  'JWT_EXPIRY=3600',
  `ANON_KEY=${apiKey('anon')}`,
  `SERVICE_ROLE_KEY=${apiKey('service_role')}`,
  `INTEGRATION_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
  '',
  '# Email for sign-up confirmation (Supabase Auth) and invitations (API).',
  ...(local
    ? [
        '# Local mail catcher: every email lands in http://localhost:8025, nothing is sent.',
        'COMPOSE_PROFILES=local-mail',
        'SMTP_HOST=mail',
        'SMTP_PORT=1025',
        '# No login: the catcher runs inside the Docker network without TLS.',
        'SMTP_USER=',
        'SMTP_PASS=',
        'SMTP_URL=smtp://mail:1025',
      ]
    : [
        '# Fill in your SMTP server. SMTP_URL is the same server for invitations, for example',
        '# smtps://user:password@smtp.example.com:465 (URL-encode special characters).',
        'COMPOSE_PROFILES=',
        'SMTP_HOST=',
        'SMTP_PORT=587',
        'SMTP_USER=',
        'SMTP_PASS=',
        'SMTP_URL=',
      ]),
  'SMTP_SENDER_EMAIL=no-reply@example.com',
  'SMTP_SENDER_NAME="[Product name]"',
  '',
  '# Sign in with Google (optional). Redirect URI to register: PUBLIC_URL/auth/v1/callback',
  'GOOGLE_ENABLED=false',
  'GOOGLE_CLIENT_ID=',
  'GOOGLE_CLIENT_SECRET=',
  '',
];
writeFileSync(file, lines.join('\n'), { mode: 0o600 });
console.log(`Wrote ${file}`);
console.log(local ? 'Next: docker compose -f deploy/docker-compose.yml up -d --build' : 'Next: fill in the SMTP settings in deploy/.env, then docker compose -f deploy/docker-compose.yml up -d --build');
console.log(`Then open ${publicUrl}`);
